"""Writes data/uat_master_v3.py (steps and expected results of Gavin's cases) from the design in build_gavin_redesign.py (the v4 master rows)."""
import os, re, sys, pprint
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "build_gavin_redesign.py"), encoding="utf-8").read()
ns = {}
sys.argv = ["x", os.devnull]
exec(src[:src.index("thin = Side(")], ns)
out = {}
for c in ns["CASES"]:
    steps, expected = [], []
    for block in re.split(r"\n(?=\d+\. )", c["Steps"].strip()):
        head, _, exp = block.partition("\n   Expected:")
        steps.append(re.sub(r"^\d+\.\s*", "", head).strip())
        expected.append(" ".join(exp.split()))
    gate = re.search(r"^Gate:\s*(.*)$", c["Setup"], re.M)
    out[c["ID"]] = {
        "title": c["Test"],
        "area": "Fee and Payment" if c["ID"].startswith("UAT-PAR") else "FAS",
        "role": c["Role"], "owner": "Gavin", "setup": c["Setup"],
        "gate": ((gate.group(1) if gate else "") + " " + c["Watch"]).strip(),
        "steps": steps, "expected": expected, "severity1": "Severity 1" in c["Watch"],
    }
text = ('"""Gavin cases of uat-master v4 (roles/qa/uat-master_v4_chain.xlsx). They replace the older copies in uat_cases_meta.py.\n'
        'Generated by tools/build_uat_meta.py from tools/build_gavin_redesign.py; change the design and regenerate, do not edit by hand."""\n'
        "from __future__ import annotations\n\nOVERRIDES: dict[str, dict] = " + pprint.pformat(out, width=150, sort_dicts=False) + "\n")
open(os.path.join(HERE, "..", "data", "uat_master_v3.py"), "w", encoding="utf-8", newline="\r\n").write(text)
print({k: (len(v["steps"]), len(v["expected"])) for k, v in out.items()})
