"""Build data/not_automated.py and docs/COVERAGE.md from the case workbook and the test files.

Usage: python tools/build_coverage.py path/to/R4_Test_Cases.xlsx
The workbook is read only. A case is "automated" when a test docstring starts with its id (for example "TC-045 ...").
"""
from __future__ import annotations

import ast
import collections
import re
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent


def load_cases(xlsx: str) -> list:
    sheet = openpyxl.load_workbook(xlsx, data_only=True).worksheets[0]
    cases = []
    for row in sheet.iter_rows(values_only=True):
        if row[0] and str(row[0]).startswith("TC-"):
            env = str(row[9] or "")
            needs = re.search(r"Needs:\s*(.*)", env)
            cases.append(dict(id=row[0], title=str(row[2]), suite=str(row[3]), env=env,
                              needs=needs.group(1).strip() if needs else "", review=str(row[19]),
                              prototype=env.startswith("Prototype")))
    return cases


def automated_map() -> dict:
    """TC id -> list of test function names (file::name) found in tests/*.py."""
    found = collections.defaultdict(list)
    for path in sorted((ROOT / "tests").glob("test_f*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_tc_"):
                match = re.match(r"test_tc_(\d{3})", node.name)
                found["TC-" + match.group(1)].append(f"{path.name}::{node.name}")
    return found


def reason(case: dict) -> str:
    if case["review"] == "Block":
        return "Blocked: no BA rule yet, the expected result cannot be written (see the assumption of the case)"
    if not case["prototype"]:
        return "Needs the F4 build: " + (case["env"].replace("\n", " ")[:160] or "environment other than the prototype")
    if case["needs"]:
        return "Needs extra seed data: " + case["needs"]
    return "Not automated"


def main(xlsx: str) -> None:
    cases = load_cases(xlsx)
    done = automated_map()
    todo = [c for c in cases if c["id"] not in done]
    lines = ['"""Cases of R4_Test_Cases.xlsx that no test automates, with the reason. Generated by tools/build_coverage.py."""',
             "from __future__ import annotations", "", "NOT_AUTOMATED = {"]
    for c in todo:
        lines.append(f'    "{c["id"]}": {reason(c)!r},')
    lines += ["}", ""]
    (ROOT / "data" / "not_automated.py").write_text("\n".join(lines), encoding="utf-8")

    by_suite = collections.OrderedDict()
    for c in cases:
        by_suite.setdefault(c["suite"], []).append(c)
    out = ["# Coverage of R4_Test_Cases.xlsx", "",
           f"Cases in the workbook: {len(cases)}. Automated: {len(cases) - len(todo)}. Not automated: {len(todo)}.", "",
           "| Suite | Cases | Automated | Not automated |", "|---|---|---|---|"]
    for suite, items in by_suite.items():
        n_done = sum(1 for c in items if c["id"] in done)
        out.append(f"| {suite} | {len(items)} | {n_done} | {len(items) - n_done} |")
    out += ["", "## Automated cases", "", "| Case | Title | Test |", "|---|---|---|"]
    for c in cases:
        if c["id"] in done:
            out.append(f'| {c["id"]} | {c["title"]} | {"<br>".join(done[c["id"]])} |')
    out += ["", "## Not automated", "", "| Case | Title | Reason |", "|---|---|---|"]
    for c in todo:
        out.append(f'| {c["id"]} | {c["title"]} | {reason(c)} |')
    (ROOT / "docs" / "COVERAGE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"automated {len(cases) - len(todo)} of {len(cases)}; wrote data/not_automated.py and docs/COVERAGE.md")


if __name__ == "__main__":
    main(sys.argv[1])
