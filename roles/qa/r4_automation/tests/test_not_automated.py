"""Every case of R4_Test_Cases.xlsx that no test automates shows up here as a skipped test with its reason,
so the report lists all 267 cases. data/not_automated.py is generated by tools/build_coverage.py."""
from __future__ import annotations

import pytest

from data.not_automated import NOT_AUTOMATED

pytestmark = pytest.mark.not_automated


@pytest.mark.parametrize("case_id", sorted(NOT_AUTOMATED))
def test_not_automated(case_id):
    pytest.skip(f"{case_id}: {NOT_AUTOMATED[case_id]}")
